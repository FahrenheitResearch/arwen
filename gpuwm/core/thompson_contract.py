"""WRF v4.6.1 Thompson ``mp_physics=8`` state and table contract.

This module is intentionally CPU-only.  It pins the state categories and the
Fortran lookup-table record layout before the CUDA process kernel is admitted.
The numerical authority is NCAR WRF v4.6.1 commit
``d66e442fccc04111067e29274c9f9eaccc3cef28``, specifically
``phys/module_mp_thompson.F``.  Classic Thompson (8) is distinct from the
aerosol-aware (28) and graupel/hail-predicting (38) packages.

WRF generates three large sequential-unformatted files on first
``thompson_init``.  gpuwm packages their validated values later, but this
reader remains the provenance gate: every record marker, shape, dtype, and
trailing byte is checked rather than treating an arbitrary binary blob as a
coefficient set.
"""

