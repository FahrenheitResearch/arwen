#!/usr/bin/env python3
"""Turn build.sh's constants.txt into gpuwm/core/kernels/
morrison_constants.cuh: every MORR_TWO_MOMENT_INIT and radar_init word
the Morrison unit reads, as C++17 hexadecimal float literals (exact by
construction).

A word equal under both morr_rimed_ice modes is one literal, MO_<name>;
a word that differs (the dense-ice AG/BG/RHOG family and the constants
derived from it) is a two-entry table read as MO_<name> through the
kernel's in-scope ``rimed`` index (0 graupel, 1 hail).  Arrays index in
Fortran order: MO_XCRG(i) is xcrg(i).

usage: make_header.py constants.txt OUTPUT.cuh
"""
import struct
import sys
from collections import defaultdict


def f32(word):
    v = struct.unpack("<f", struct.pack("<I", int(word, 16)))[0]
    return v.hex() + "f" if v != 0.0 else "0.0f"


def f64(word):
    v = struct.unpack("<d", struct.pack("<Q", int(word, 16)))[0]
    return v.hex() if v != 0.0 else "0.0"


def main(argv):
    # data[kind][name][mode][index] = word
    data = {k: defaultdict(lambda: defaultdict(dict)) for k in "RDI"}
    for line in open(argv[1]):
        kind, name, mode, i, word = line.split()
        data[kind][name][int(mode)][int(i)] = word
    out = ["// GENERATED by tools/morrison_constants/make_header.py from WRF",
           "// v4.6.1 MORR_TWO_MOMENT_INIT and radar_init's own words",
           "// (tools/morrison_constants/build.sh, both morr_rimed_ice modes).",
           "// Do not edit: regenerate.",
           "#pragma once", ""]
    for kind, conv, ctype in (("R", f32, "float"), ("D", f64, "double")):
        for name in sorted(data[kind], key=str.lower):
            modes = data[kind][name]
            n = max(modes[0])
            same = all(modes[0][i] == modes[1][i] for i in range(1, n + 1))
            macro = name.upper()
            if same and n == 1:
                out.append(f"#define MO_{macro} ({conv(modes[0][1])})")
            elif same:
                body = ", ".join(conv(modes[0][i]) for i in range(1, n + 1))
                out.append(f"__device__ __constant__ {ctype} mo_{name}[{n}] "
                           f"= {{{body}}};")
                out.append(f"#define MO_{macro}(i) (mo_{name}[(i) - 1])")
            elif n == 1:
                body = ", ".join(conv(modes[m][1]) for m in (0, 1))
                out.append(f"__device__ __constant__ {ctype} mo_{name}[2] "
                           f"= {{{body}}};")
                out.append(f"#define MO_{macro} (mo_{name}[rimed])")
            else:
                rows = ", ".join(
                    "{" + ", ".join(conv(modes[m][i]) for i in range(1, n + 1))
                    + "}" for m in (0, 1))
                out.append(f"__device__ __constant__ {ctype} mo_{name}[2][{n}]"
                           f" = {{{rows}}};")
                out.append(f"#define MO_{macro}(i) (mo_{name}[rimed][(i) - 1])")
    for name in sorted(data["I"], key=str.lower):
        modes = data["I"][name]
        if modes[0][1] == modes[1][1]:
            out.append(f"#define MO_{name.upper()} ({modes[0][1]})")
        else:
            out.append(f"#define MO_{name.upper()} ((rimed) ? "
                       f"{modes[1][1]} : {modes[0][1]})")
    open(argv[2], "w", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
