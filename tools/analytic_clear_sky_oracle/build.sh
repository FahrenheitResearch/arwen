#!/usr/bin/env bash
# Build and run the WRF v4.6.1 side of the ra=90 (analytic clear-sky) column
# oracle: radconst + calc_coszen, the radiation-call COSZEN carrier.
#
# usage: build.sh WRF_SOURCE_ROOT WRF_SERIAL_BUILD_ROOT BUILD_DIR cz_in.bin
#
#   WRF_SOURCE_ROOT        pristine WRF tree at the pinned v4.6.1 commit
#   WRF_SERIAL_BUILD_ROOT  a built WRF tree whose external/esmf_time_f90 holds
#                          WRF's own time library (libesmf_time.a + .mod)
#
# The two routines are taken from phys/module_radiation_driver.F by line
# range, byte for byte, into a module wrapper (no statement is edited); the
# three model constants they are called with (DEGRAD, DPD) are lines 72-74
# of share/module_model_constants.F, also byte for byte.
#
# Two builds of the same untouched routines:
#   O0     the REFERENCE: every SIN/COS/ASIN is one scalar libm call.
#   O2vec  WRF's GNU phys/ flags (-O2 -ftree-vectorize -funroll-loops), to
#          measure whether stock WRF on this toolchain differs from O0 (the
#          vectoriser may call libmvec's vector sinf/cosf).
set -euo pipefail

if [[ $# -ne 4 ]]; then
    echo "usage: build.sh WRF_SOURCE_ROOT WRF_SERIAL_BUILD_ROOT BUILD_DIR cz_in.bin" >&2
    exit 2
fi
source_root=$(realpath "$1")
serial_root=$(realpath "$2")
build_dir=$(realpath -m "$3")
input=$(realpath "$4")
script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
pinned_commit="d66e442fccc04111067e29274c9f9eaccc3cef28"
driver_src="${source_root}/phys/module_radiation_driver.F"
const_src="${source_root}/share/module_model_constants.F"
esmf="${serial_root}/external/esmf_time_f90"

head_commit=$(git -C "${source_root}" rev-parse HEAD)
if [[ "${head_commit}" != "${pinned_commit}" ]]; then
    echo "WRF tree is at ${head_commit}, not the pinned ${pinned_commit}" >&2
    exit 3
fi
if ! git -C "${source_root}" diff --quiet HEAD -- phys/module_radiation_driver.F \
        share/module_model_constants.F external/esmf_time_f90; then
    echo "a source this oracle reads differs from the pinned commit" >&2
    exit 3
fi
test -f "${esmf}/libesmf_time.a"
test -f "${esmf}/module_utility.mod"

mkdir -p "${build_dir}"
cd "${build_dir}"

# The extracted text must be exactly the routines and constants named above.
sed -n '3469,3511p' "${driver_src}" > radconst.txt
sed -n '3514,3541p' "${driver_src}" > calc_coszen.txt
sed -n '72,74p' "${const_src}" > constants.txt
grep -q '^   SUBROUTINE radconst(XTIME,DECLIN,SOLCON,JULIAN, ' radconst.txt
grep -q '^   END SUBROUTINE radconst$' radconst.txt
grep -q '^   SUBROUTINE calc_coszen(' calc_coszen.txt
grep -q '^   END SUBROUTINE calc_coszen$' calc_coszen.txt
grep -q 'piconst *= 3.1415926535897932384626433' constants.txt
grep -q 'DEGRAD *= piconst/180.' constants.txt
grep -q 'DPD *= 360./365.' constants.txt

{
    echo "! generated by build.sh from share/module_model_constants.F:72-74 (WRF ${pinned_commit})"
    echo "module wrf461_model_constants"
    cat constants.txt
    echo "end module wrf461_model_constants"
} > wrf461_model_constants.f90
{
    echo "! generated by build.sh: module_wrf_error is USEd by radconst, which calls nothing from it"
    echo "module module_wrf_error"
    echo "end module module_wrf_error"
    echo "! WRF's time library reports a malformed time through this frame routine"
    echo "subroutine wrf_error_fatal(message)"
    echo "  character(len=*), intent(in) :: message"
    echo "  write(0,*) trim(message)"
    echo "  error stop 1"
    echo "end subroutine wrf_error_fatal"
} > module_wrf_error_stub.f90
{
    echo "! generated by build.sh from phys/module_radiation_driver.F:3469-3511 and :3514-3541"
    echo "! (WRF ${pinned_commit}); the routine text below is unedited"
    echo "module wrf461_coszen"
    echo "contains"
    cat radconst.txt
    echo
    cat calc_coszen.txt
    echo "end module wrf461_coszen"
} > wrf461_coszen.f90

COMMON="-ffree-form -ffree-line-length-none -fconvert=big-endian -frecord-marker=4 -fallow-argument-mismatch"

build_variant() {
    local tag=$1; shift
    local opt="$*"
    mkdir -p "${tag}"
    ( cd "${tag}"
      gfortran -c ${opt} ${COMMON} ../wrf461_model_constants.f90
      gfortran -c ${opt} ${COMMON} ../module_wrf_error_stub.f90
      gfortran -c ${opt} ${COMMON} ../wrf461_coszen.f90
      gfortran -c ${opt} ${COMMON} -I . -I "${esmf}" "${script_dir}/run_coszen.F90"
      gfortran -o run_coszen run_coszen.o wrf461_coszen.o module_wrf_error_stub.o \
          wrf461_model_constants.o "${esmf}/libesmf_time.a"
      nm -u wrf461_coszen.o | sed 's/^ *//' | sort > undefined.txt )
}

build_variant O0 -O0
if grep -q '_ZGV' O0/undefined.txt; then
    echo "-O0 object pulled in a libmvec vector symbol" >&2
    exit 4
fi
build_variant O2vec -O2 -ftree-vectorize -funroll-loops

{
    echo "# gfortran: $(gfortran --version | head -1)"
    echo "# C library: $(ldd --version | head -1)"
    echo "# -O0 (THE REFERENCE) math symbols of the extracted routines:"
    grep -E 'sin|cos|asin|_ZGV' O0/undefined.txt || true
    echo "# -O2 -ftree-vectorize -funroll-loops (WRF's GNU phys/ flags):"
    grep -E 'sin|cos|asin|_ZGV' O2vec/undefined.txt || true
} > libmvec-report.txt
cat libmvec-report.txt

( cd O0 && ./run_coszen "${input}" ../cz-out-O0.bin )
( cd O2vec && ./run_coszen "${input}" ../cz-out-O2vec.bin )

sha256sum "${driver_src}" "${const_src}" "${esmf}/libesmf_time.a" \
    "${script_dir}/run_coszen.F90" wrf461_coszen.f90 wrf461_model_constants.f90 \
    "${input}" cz-out-O0.bin cz-out-O2vec.bin > oracle-sha256sums.txt
gfortran --version | head -1 > compiler.txt
echo "oracle built and run in ${build_dir}"
