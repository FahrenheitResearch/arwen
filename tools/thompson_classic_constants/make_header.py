#!/usr/bin/env python3
"""Turn build.sh's constants.txt into gpuwm/core/kernels/
thompson_classic_constants.cuh: every thompson_init word classic Thompson
reads, as C++17 hexadecimal float literals (exact by construction), with
Fortran-order index macros.

usage: make_header.py constants.txt OUTPUT.cuh
"""
import struct
import sys
from collections import defaultdict

# Fortran shapes (column-major) of the dumped arrays.
SHAPES = {"cce": (5, 15), "ccg": (5, 15), "cge": (12, 9), "cgg": (12, 9)}


def f32(word):
    v = struct.unpack("<f", struct.pack("<I", int(word, 16)))[0]
    return v.hex() + "f" if v != 0.0 else "0.0f"


def f64(word):
    v = struct.unpack("<d", struct.pack("<Q", int(word, 16)))[0]
    return v.hex() if v != 0.0 else "0.0"


def main(argv):
    reals, doubles, ints = defaultdict(dict), defaultdict(dict), {}
    for line in open(argv[1]):
        kind, name, i, word = line.split()
        if kind == "R":
            reals[name][int(i)] = word
        elif kind == "D":
            doubles[name][int(i)] = word
        else:
            ints[name] = int(word)
    out = ["// GENERATED by tools/thompson_classic_constants/make_header.py from",
           "// WRF v4.6.1 thompson_init's own words (tools/thompson_classic_"
           "constants/build.sh).",
           "// Do not edit: regenerate.  Classic (non-hail) state: av_g/bv_g "
           "carry av_g_old/bv_g_old in slot idx_bg1 = 5.",
           "#pragma once", ""]
    for name in sorted(reals):
        vals = reals[name]
        if len(vals) == 1 and name not in SHAPES and 1 in vals and name not in (
                "ocg1", "ocg2", "cie", "cig", "cre", "crg", "cse", "csg",
                "oamg", "ocmg", "av_g", "bv_g"):
            out.append(f"#define TC_{name} ({f32(vals[1])})")
            continue
        n = max(vals)
        body = ", ".join(f32(vals[i]) for i in range(1, n + 1))
        out.append(f"__device__ __constant__ float tc_{name}[{n}] = {{{body}}};")
        if name in SHAPES:
            rows = SHAPES[name][0]
            out.append(f"#define TC_{name.upper()}(i, j) "
                       f"(tc_{name}[((i) - 1) + {rows} * ((j) - 1)])")
        else:
            out.append(f"#define TC_{name.upper()}(i) (tc_{name}[(i) - 1])")
    for name in sorted(doubles):
        vals = doubles[name]
        n = max(vals)
        if n == 1:
            out.append(f"#define TC_{name} ({f64(vals[1])})")
            continue
        body = ", ".join(f64(vals[i]) for i in range(1, n + 1))
        out.append(f"__device__ __constant__ double tc_{name}[{n}] = {{{body}}};")
        out.append(f"#define TC_{name.upper()}(i) (tc_{name}[(i) - 1])")
    for name in sorted(ints):
        out.append(f"#define TC_{name} ({ints[name]})")
    open(argv[2], "w", newline="\n").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main(sys.argv)
