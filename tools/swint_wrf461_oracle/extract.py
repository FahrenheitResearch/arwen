"""Cut the four swint_opt = 1 routines out of byte-unmodified WRF v4.6.1.

Usage: python extract.py WRF_SOURCE_ROOT OUTPUT.F90

module_radiation_driver.F cannot be compiled alone (it USEs every
radiation scheme), so the routines the driver runs for swint_opt = 1 are
copied out of it by name, text unchanged, into one module:

  radconst                    the declination (module_radiation_driver.F:3469)
  calc_coszen                 the zenith cosine, with the v4.3 clamp (:3514)
  update_swinterp_parameters  the per-call power-law fit (:3543)
  interp_sw_radiation         the every-step evaluation, with the v3.9.1
                              exponent-zero fallback (:3626)

radconst carries ``USE module_wrf_error`` and calls nothing from it; an
empty stand-in module satisfies the USE.  Nothing else is added: every
statement between SUBROUTINE and END SUBROUTINE is WRF's own line.  The
sha256 of the source file and of each extracted routine are printed so the
build receipt pins them.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROUTINES = ("radconst", "calc_coszen", "update_swinterp_parameters",
            "interp_sw_radiation")
SOURCE = "phys/module_radiation_driver.F"
SOURCE_SHA256 = (
    "779875651512709c47d50ef6c1e1216ad94726f1996c5e45a0db8eb800733ffa")


def cut(lines, name):
    start = re.compile(rf"^\s*subroutine\s+{name}\s*\(", re.I)
    end = re.compile(rf"^\s*end\s+subroutine\s+{name}\s*$", re.I)
    begin = [i for i, line in enumerate(lines) if start.match(line)]
    if len(begin) != 1:
        raise SystemExit(f"{name}: {len(begin)} SUBROUTINE lines")
    for j in range(begin[0], len(lines)):
        if end.match(lines[j]):
            return lines[begin[0]:j + 1]
    raise SystemExit(f"{name}: no END SUBROUTINE")


def main() -> None:
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    raw = (root / SOURCE).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise SystemExit(f"{SOURCE} sha256 {digest} != pinned {SOURCE_SHA256}")
    lines = raw.decode("ascii").splitlines()
    body = []
    print(f"source {SOURCE} sha256 {digest}")
    for name in ROUTINES:
        text = cut(lines, name)
        if any(line.lstrip().startswith("#") for line in text):
            raise SystemExit(f"{name}: preprocessor line inside the routine")
        h = hashlib.sha256("\n".join(text).encode()).hexdigest()
        print(f"routine {name} lines {len(text)} sha256 {h}")
        body.extend(text)
        body.append("")
    module = [
        "! Generated by tools/swint_wrf461_oracle/extract.py from WRF v4.6.1",
        f"! {SOURCE} (sha256 {digest}); routine text unchanged.",
        "module module_wrf_error",
        "end module module_wrf_error",
        "",
        "module swint_wrf461",
        "implicit none",
        "contains",
        *body,
        "end module swint_wrf461",
        "",
    ]
    out.write_text("\n".join(module), encoding="ascii")


if __name__ == "__main__":
    main()
