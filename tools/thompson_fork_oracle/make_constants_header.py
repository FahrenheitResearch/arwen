#!/usr/bin/env python3
"""Turn build_constants.sh's fork_constants.txt into
gpuwm/core/kernels/thompson_fork_constants.cuh: every derived constant and
PARAMETER the fork's runtime reads, as its exact bit pattern (C++17
hexadecimal floating literals), so thompson_fork.cu starts from the words
the Fortran's thompson_init and radar_init left in memory.

usage: make_constants_header.py fork_constants.txt OUT.cuh

Scalars become ``constexpr`` values TF_<name>; arrays become ``__constant__``
arrays TF_<name>[n] in Fortran element order (0-based: Fortran element i is
[i-1]; a 2-D array (a, b) is [(a-1) + dim1*(b-1)]).  Complex scalars are two
doubles, TF_<name>_RE and TF_<name>_IM.
"""

from __future__ import annotations

import hashlib
import struct
import sys
from collections import OrderedDict
from pathlib import Path

#: Arrays the runtime indexes at run time (kept as __constant__ arrays).
#: Every other name with one element is a scalar.
ARRAY_DIMS = {"cce": (5, 15), "ccg": (5, 15)}


def f32_literal(bits: int) -> str:
    value = struct.unpack("<f", struct.pack("<I", bits))[0]
    if value == 0.0:
        return "-0.0f" if bits & 0x80000000 else "0.0f"
    return float(value).hex() + "f"


def f64_literal(bits: int) -> str:
    value = struct.unpack("<d", struct.pack("<Q", bits))[0]
    if value == 0.0:
        return "-0.0" if bits >> 63 else "0.0"
    return float(value).hex()


def parse(path):
    entries = OrderedDict()
    for line in Path(path).read_text().splitlines():
        name, index, kind, value = line.split()
        entries.setdefault(name, []).append((int(index), kind, value))
    return entries


def render(entries, source_sha):
    out = [
        "// GENERATED by tools/thompson_fork_oracle/make_constants_header.py",
        "// from the fork's own thompson_init/radar_init (build_constants.sh),",
        f"// fork_constants.txt sha256 {source_sha}.  Do not edit by hand.",
        "//",
        "// Every value is the exact word the HRRR v4.1.21 fork's Fortran held",
        "// (module_mp_thompson.F sha256 4d600111..., module_mp_radar.F",
        "// 08329c87...), identical under glibc 2.39 and 2.43.",
        "#pragma once",
        "",
    ]
    for name, items in entries.items():
        kind = items[0][1]
        n = len(items)
        if name in ("m_w_0", "m_i_0"):
            re_bits = int(items[0][2], 16)
            im_bits = int(items[1][2], 16)
            out.append(f"constexpr double TF_{name}_RE = "
                       f"{f64_literal(re_bits)};")
            out.append(f"constexpr double TF_{name}_IM = "
                       f"{f64_literal(im_bits)};")
            continue
        if kind == "i":
            out.append(f"constexpr int TF_{name} = {int(items[0][2])};")
            continue
        lit = f32_literal if kind == "f" else f64_literal
        ctype = "float" if kind == "f" else "double"
        if n == 1 and name not in ARRAY_DIMS:
            out.append(f"constexpr {ctype} TF_{name} = "
                       f"{lit(int(items[0][2], 16))};")
            continue
        values = [lit(int(v, 16)) for _, _, v in items]
        dims = ARRAY_DIMS.get(name)
        note = f"  // Fortran ({', '.join(map(str, dims))})" if dims else ""
        out.append(f"__constant__ {ctype} TF_{name}[{n}] = {{{note}")
        for i in range(0, n, 4):
            out.append("    " + ", ".join(values[i:i + 4]) + ",")
        out.append("};")
    out.append("")
    return "\n".join(out)


def main(argv):
    if len(argv) != 3:
        print(__doc__)
        return 2
    raw = Path(argv[1]).read_bytes()
    text = render(parse(argv[1]), hashlib.sha256(raw).hexdigest())
    Path(argv[2]).write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
