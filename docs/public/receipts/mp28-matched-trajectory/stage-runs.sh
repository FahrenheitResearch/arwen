#!/bin/bash
set -e
T=mp28traj
NX=120; NZ=40; DX=2000; ZTOP=20000; DT=12; RUNMIN=120; HIST=10
mkdir -p $T/runs
# --- initial conditions: ONE ideal.exe (stock build) per mp option ---
for MP in 8 28; do
  D=$T/runs/ic-mp$(printf %02d $MP)
  rm -rf $D; mkdir -p $D; cd $D
  ln -sf $T/WRF-4.6.1/main/ideal.exe .
  ln -sf $T/input_sounding .
  bash $T/mknml.sh namelist.input $MP $NX $NZ $DX $ZTOP $DT $RUNMIN $HIST
  ./ideal.exe > ideal.log 2>&1
  echo "ic mp=$MP rc=$? $(ls -la wrfinput_d01 | awk '{print $5}') bytes"
done
# --- four WRF forecast runs ---
for BUILD in vec novec; do
  case $BUILD in
    vec)   SRC=$T/WRF-4.6.1 ;;
    novec) SRC=$T/WRF-4.6.1-novec ;;
  esac
  for MP in 8 28; do
    TAG=wrf-$BUILD-mp$(printf %02d $MP)
    D=$T/runs/$TAG
    rm -rf $D; mkdir -p $D; cd $D
    ln -sf $SRC/main/wrf.exe .
    ln -sf $T/input_sounding .
    cp $T/runs/ic-mp$(printf %02d $MP)/namelist.input .
    cp $T/runs/ic-mp$(printf %02d $MP)/wrfinput_d01 .
    cp $SRC/run/CCN_ACTIVATE.BIN .
    echo "staged $TAG"
  done
done
# --- lookup tables: each BUILD gets its own, generated by that build ---
cp $T/probe28/freezeH2O.dat $T/probe28/qr_acr_qg_V4.dat $T/probe28/qr_acr_qsV2.dat \
   $T/runs/wrf-vec-mp08/ 
cp $T/probe28/freezeH2O.dat $T/probe28/qr_acr_qg_V4.dat $T/probe28/qr_acr_qsV2.dat \
   $T/runs/wrf-vec-mp28/
echo "vec tables copied (generated by the stock build in probe28)"
