@pytest.mark.parametrize('word', [1, 71362, 0x007fffff, 0x80000001,
                                 0x800116c2, 0x807fffff])
def test_boundary_flush_keeps_zero_sign(word):
    value = np.array([word], np.uint32).view(np.float32)[0]
    boundary = _F32Boundary(True)
    sign = word & 0x80000000
    for result in (boundary.widen(value), boundary.narrow(value),
                   boundary.mul(value, 1.), boundary.sub(value, 0.)):
        assert np.float32(result).view(np.uint32) == sign
    for result in (_F32Boundary(False).widen(value), _F32Boundary(False).narrow(value)):
        assert np.float32(result).view(np.uint32) == word


def test_float32_operations_flush_inputs_and_rounded_results():
    normal = float.fromhex('0x1p-126')
    next_normal = float(np.nextafter(np.float32(normal), np.float32(np.inf)))
    off, on = _F32Boundary(False), _F32Boundary(True)
    assert off.sub(next_normal, normal) == float.fromhex('0x1p-149')
    assert on.sub(next_normal, normal) == 0.
    assert on.add(next_normal, -normal) == 0.
    assert off.mul(1.e-20, 1.e-20) > 0.
    assert on.mul(1.e-20, 1.e-20) == 0.
    assert off.sqrt(float.fromhex('0x1p-149')) > 0.
    assert on.sqrt(float.fromhex('0x1p-149')) == 0.
    # Widening must preserve normals, including the least normal value.
    assert on.widen(normal) == normal


