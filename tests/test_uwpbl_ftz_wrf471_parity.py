def _assert_words(got, want, label):
    assert got.dtype == want.dtype, label
    assert got.shape == want.shape, label
    different = got.view(np.uint32) != want.view(np.uint32)
    assert not different.any(), f'{label}: {np.count_nonzero(different)} different words'
    return want.size


def _positions(got, want, step):
    words = set()
    for name in FIELDS:
        for index in np.argwhere(got[name].view(np.uint32) != want[name].view(np.uint32)):
            words.add((int(index[0])+1, step, name,
                       int(index[1])+1 if len(index) == 2 else 1))
    return words


