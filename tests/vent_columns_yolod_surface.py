def _sat(th, qv, qc, p):
    """(membership on the registered qt >= qs test, theta_es) from the
    same Tetens-liquid constants gpuwm.verify.sase_ref.moist_n2 uses."""
    t = th * (p / _P0) ** (_RD / _CP)
    es = 1000.0 * _SVP1 * np.exp(_SVP2 * (t - _SVPT0) / (t - _SVP3))
    qs = _EP2 * es / (p - es)
    return (qv + qc) >= qs, th * np.exp(_XLV * qs / (_CP * t))


def _lowest_run(memb, min_cells=2):
    """The lowest contiguous run of >= min_cells member cells -- the
    authority's step 1 (its bulk theta_es reading is asserted below)."""
    k = 0
    while k < len(memb):
        if not memb[k]:
            k += 1
            continue
        s = k
        while k + 1 < len(memb) and memb[k + 1]:
            k += 1
        if k - s >= min_cells - 1:
            return s, k
        k += 1
    return None


