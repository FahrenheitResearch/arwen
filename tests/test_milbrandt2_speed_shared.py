@pytest.mark.parametrize("nz", [49, 65])
def test_shared_sedimentation_bits(nz):
    cp = pytest.importorskip("cupy")
    try:
        if cp.cuda.runtime.getDeviceCount() == 0:
            pytest.skip("CUDA device unavailable")
    except cp.cuda.runtime.CUDARuntimeError:
        pytest.skip("CUDA device unavailable")
    from gpuwm.core.kernels import _preamble, module_source
    from gpuwm.core.milbrandt2_constants import ck_vector_device
    base = cp.RawModule(code=_preamble() + _base_source(), options=("-std=c++17",))
    new = cp.RawModule(code=module_source("milbrandt2"), options=("-std=c++17",))
    rng = np.random.default_rng(719)
    shape = (nz, 2, 19)
    fields = []
    fields.append(cp.asarray(rng.uniform(220, 290, shape).astype(np.float32)))
    fields.append(cp.full(shape, 0.003, cp.float32))
    for i in range(6):
        mass = rng.uniform(1.e-8, 1.e-3, shape).astype(np.float32)
        mass[rng.random(shape) < 0.3] = 0
        fields.append(cp.asarray(mass))
    for i in range(6):
        fields.append(cp.asarray(rng.uniform(100, 1.e5, shape).astype(np.float32)))
    density = cp.asarray(np.broadcast_to(np.linspace(1.2, 0.1, nz,
        dtype=np.float32)[:, None, None], shape).copy())
    depth = cp.asarray(rng.uniform(100, 500, shape).astype(np.float32))
    fields.extend([density, 1 / density, depth, 1 / depth, cp.sqrt(1.225 / density)])
    fields.extend([cp.zeros(shape[1:], cp.float32) for _ in range(9)])
    fields.append(ck_vector_device())
    a = tuple(x.copy() for x in fields) + (np.float32(15), np.int32(nz), np.int32(2), np.int32(19))
    b = tuple(x.copy() for x in fields) + a[-4:]
    tier = 64 if nz <= 64 else 256
    flux = cp.empty((5, 2, 19), cp.float32)
    base.get_function("milbrandt2_sediment_" + str(tier))((2,), (32,), a)
    new.get_function("milbrandt2_sediment_" + str(tier))(
        (2,), (32, 5), b, shared_mem=5 * 32 * 4)
    for i in range(len(fields)):
        assert cp.asnumpy(a[i]).tobytes() == cp.asnumpy(b[i]).tobytes(), i
