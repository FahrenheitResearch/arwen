"""LW extension geometry against an admitted WRF 4.7.1 solver boundary.

The stored native expectations are not regenerated by the implementation.
GPU-marked tests exercise the actual rp_prep kernel, including partial blocks.
"""
from hashlib import sha256
import json
import math
import os
from pathlib import Path

import numpy as np
import pytest

from gpuwm.core import rrtmg_legacy_prep as prep

DATA = Path(__file__).parent / "data" / "wrf471_lw_extension"
FIELDS = ("plev", "play", "tlev", "tlay", "o3vmr")
SURFACES = {"tsk", "emiss", "xland", "xice", "snow", "xlat"}
F = np.float32


def assert_words(actual, expected, field):
    assert np.asarray(actual).dtype == np.dtype(F), field + " must be float32"
    actual = np.ascontiguousarray(actual, dtype=F)
    expected = np.ascontiguousarray(expected, dtype=F)
    assert actual.shape == expected.shape, field
    np.testing.assert_array_equal(actual.view(np.uint32),
                                  expected.view(np.uint32), err_msg=field)


@pytest.fixture(scope="module")
def native():
    provenance = json.loads((DATA / "provenance.json").read_text())
    file = DATA / provenance["array_file"]
    assert sha256(file.read_bytes()).hexdigest() == provenance["array_sha256"]
    assert provenance["accepted_source_artifact_sha256"]["main/wrf.exe"] == (
        "7680ed5b3483c7ab3d90589707a15fb2bb524cecd7de78948619b4ce794c2de8")
    with np.load(file, allow_pickle=False) as archive:
        values = {name: archive[name].copy() for name in archive.files}
    inputs = {name.removeprefix("input__"): value[()] if value.ndim == 0
              else value for name, value in values.items()
              if name.startswith("input__")}
    expected = {name: values["expected__" + name] for name in FIELDS}
    assert inputs["p8w"][-1] == F(5000)
    assert inputs["nlayers"] == 62 and inputs["p3d"].size == 49
    return inputs, expected


