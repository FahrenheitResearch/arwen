@pytest.mark.gpu
def test_actual_device_threshold_shallow_and_single_extra_paths(native):
    if os.environ.get("GPUWM_NO_LOCAL_GPU") == "1":
        pytest.skip("GPU execution requires an authorized remote device")
    cp = pytest.importorskip("cupy")
    from gpuwm.core.rrtmg_legacy_device import lwrad_prep_batch_device
    inputs = edge_inputs(native)
    device = {name: cp.asarray(value) if isinstance(value, np.ndarray)
              else value for name, value in inputs.items()}
    actual = {field: cp.asnumpy(value) for field, value in
              lwrad_prep_batch_device(**device).items() if field in FIELDS}
    assert_edge_geometry(actual, inputs)
    host = prep.lwrad_prep_batch(**inputs)
    for field in FIELDS:
        assert_words(actual[field], host[field], field)
    device["nlayers"] = 50
    one = lwrad_prep_batch_device(**device)
    assert_words(cp.asnumpy(one["plev"])[:, 49:],
                 np.column_stack((inputs["p8w"][:, -1] / F(100),
                                  np.zeros(5, dtype=F))), "device one extra")
    inputs["nlayers"] = 50
    host_one = prep.lwrad_prep_batch(**inputs)
    for field in FIELDS:
        assert_words(cp.asnumpy(one[field]), host_one[field], field)
    device["nlayers"] = 49
    with pytest.raises(ValueError, match="at least kte\\+1"):
        lwrad_prep_batch_device(**device)
