def batch_inputs(native, count, tops_pa=None):
    inputs, _ = native
    result = {}
    for name, value in inputs.items():
        if isinstance(value, np.ndarray):
            result[name] = np.repeat(value[None, :], count, axis=0)
        elif name in SURFACES:
            result[name] = np.full(count, value, dtype=F)
        else:
            result[name] = value
    if tops_pa is not None:
        result["p8w"][:, -1] = np.asarray(tops_pa, dtype=F)
        result["p3d"][:, -1] = F(.5) * (
            result["p8w"][:, -2] + result["p8w"][:, -1])
    return result


def scalar_inputs(batch, column):
    return {name: value[column] if isinstance(value, np.ndarray) else value
            for name, value in batch.items()}


def test_native_fixture_contains_original_four_hpa_grid(native):
    _, expected = native
    # Literal independent native words catch a fixture or count regression.
    assert_words(expected["plev"][-14:],
                 [50, 46, 42, 38, 34, 30, 26, 22, 18, 14, 10, 6, 2, 0],
                 "native interfaces")
    assert_words(expected["play"][-13:],
                 [48, 44, 40, 36, 32, 28, 24, 20, 16, 12, 8, 4, 1],
                 "native midpoints")


def test_scalar_prep_matches_native_pressure_temperature_and_ozone(native):
    inputs, expected = native
    actual = prep.lwrad_prep(**inputs)
    for field in FIELDS:
        assert_words(actual[field], expected[field], field)


def test_native_profile_words_do_not_call_platform_transcendentals(native, monkeypatch):
    # Pressure-linear temperature interpolation and pressure-thickness ozone
    # averaging must not pin glibc/UCRT exp/log/pow/trig results. The separate
    # trace-gas EXP uses the existing deterministic noahmp_libm transcription.
    def refused(*args, **kwargs):
        raise AssertionError("native LW profile words must not use platform libm")

    for name in ("exp", "expm1", "log", "log10", "log1p", "pow", "sqrt",
                 "sin", "cos", "tan", "asin", "acos", "atan", "atan2"):
        monkeypatch.setattr(math, name, refused)
    for name in ("exp", "expm1", "log", "log10", "log1p", "power", "sqrt",
                 "sin", "cos", "tan", "arcsin", "arccos", "arctan", "arctan2"):
        monkeypatch.setattr(np, name, refused)
    inputs, expected = native
    actual = prep.lwrad_prep(**inputs)
    for field in FIELDS:
        assert_words(actual[field], expected[field], field)


