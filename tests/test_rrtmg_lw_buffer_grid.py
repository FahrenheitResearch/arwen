@pytest.mark.parametrize("top_pa,extras,levels", [
    (5000, 13, [50, 46, 42, 38, 34, 30, 26, 22, 18, 14, 10, 6, 2, 0]),
    (4800, 12, [48, 44, 40, 36, 32, 28, 24, 20, 16, 12, 8, 4, 0]),
    (5200, 13, [52, 48, 44, 40, 36, 32, 28, 24, 20, 16, 12, 8, 4, 0]),
    (200, 1, [2, 0]),
    (600, 2, [6, 2, 0]),
])
def test_ordinary_tops_keep_wrf_nint_count_and_four_hpa_grid(
        native, top_pa, extras, levels):
    inputs = batch_inputs(native, 1, [top_pa])
    inputs["nlayers"] = prep.compute_lw_nlayers(50, F(top_pa))
    assert inputs["nlayers"] == 49 + extras
    actual = prep.lwrad_prep(**scalar_inputs(inputs, 0))
    assert_words(actual["plev"][49:], levels, "ordinary top interfaces")


def test_nint_count_half_tie_and_adjacent_input_words():
    tie = F(5000)
    below = np.nextafter(tie, F(-np.inf))
    above = np.nextafter(tie, F(np.inf))
    assert prep.compute_lw_nlayers(50, below) == 49 + 12
    assert prep.compute_lw_nlayers(50, tie) == 49 + 13
    assert prep.compute_lw_nlayers(50, above) == 49 + 13


def edge_inputs(native):
    # Adjacent Pa words convert to the adjacent hPa words around 48.
    threshold = F(4800)
    tops = np.array([5000, np.nextafter(threshold, F(-np.inf)), threshold,
                     np.nextafter(threshold, F(np.inf)), 100], dtype=F)
    return batch_inputs(native, tops.size, tops)


def assert_edge_geometry(actual, inputs):
    tops = np.asarray(inputs["p8w"][:, -1] / F(100), dtype=F)
    assert_words(tops[1:4], [np.nextafter(F(48), F(-np.inf)), F(48),
                            np.nextafter(F(48), F(np.inf))],
                 "adjacent converted threshold words")
    levels = np.asarray(actual["plev"][:, 49:], dtype=F)
    assert np.all(levels[:, :-1] > 0)
    assert np.all(np.diff(levels, axis=1) < 0)
    assert np.all(np.asarray(actual["play"]) > 0)
    assert_words(levels[:, -1], np.zeros(tops.size, dtype=F), "terminal zero")
    # The safe adjacent-up column must keep four, even though 13*4 > top.
    assert_words(levels[[0, 3], 1], tops[[0, 3]] - F(4), "safe step")
    # Equality and next-down must preserve the original conservative fallback.
    for column in (1, 2, 4):
        step = F(tops[column] / F(13))
        want = [tops[column]]
        for _ in range(12):
            want.append(F(want[-1] - step))
        want.append(F(0))
        assert_words(levels[column], want, "retained shallow fallback")
    for field in FIELDS:
        assert np.isfinite(np.asarray(actual[field])).all(), field


def test_mixed_shallow_columns_and_threshold_words(native):
    inputs = edge_inputs(native)
    actual = prep.lwrad_prep_batch(**inputs)
    assert_edge_geometry(actual, inputs)
    for column in range(5):
        scalar = prep.lwrad_prep(**scalar_inputs(inputs, column))
        for field in FIELDS:
            assert_words(actual[field][column], scalar[field], field)


def test_single_extra_layer_has_only_the_terminal_zero(native):
    inputs = batch_inputs(native, 2, [200, 5000])
    inputs["nlayers"] = 50
    actual = prep.lwrad_prep_batch(**inputs)
    assert_words(actual["plev"][:, 49:], [[2, 0], [50, 0]], "one extra")
    assert_words(actual["play"][:, 49], [1, 25], "one extra midpoint")
    for column in range(2):
        scalar = prep.lwrad_prep(**scalar_inputs(inputs, column))
        for field in FIELDS:
            assert np.isfinite(actual[field]).all(), field
            assert_words(actual[field][column], scalar[field], field)


def test_zero_extra_layers_remain_refused(native):
    inputs = batch_inputs(native, 1)
    inputs["nlayers"] = 49
    for function, kwargs in ((prep.lwrad_prep_batch, inputs),
                             (prep.lwrad_prep, scalar_inputs(inputs, 0))):
        with pytest.raises(ValueError, match="at least kte\\+1"):
            function(**kwargs)


