# the point of the extraction: no domain is privileged
# --------------------------------------------------------------------------


def _echo_pair(shape=(9, 11)):
    left = np.zeros(shape, dtype=np.float64)
    right = np.zeros(shape, dtype=np.float64)
    left[2:5, 2:5] = 50.0
    right[4:7, 5:8] = 50.0
    return left, right


def test_fss_is_scored_on_every_domain_of_a_two_domain_pair():
    """A parent and a child, same physical radius, different spacings."""
    left, right = _echo_pair()
    fields = {600: left[None, ...], 1200: left[None, ...]}
    other = {600: right[None, ...], 1200: right[None, ...]}
    scored = {
        domain: field_metrics.mean_fss_distance(
            fields, other, threshold=40.0, radius_m=5000.0, dx_m=dx,
            times=(600, 1200))
        for domain, dx in (("parent", 12000.0), ("child", 3000.0))
    }
    assert set(scored) == {"parent", "child"}
    assert all(0.0 <= value <= 1.0 for value in scored.values())
    # The radius is physical, so the coarse domain sees the two echoes inside
    # one neighborhood and the fine domain does not: the distances differ, and
    # neither call named a domain.
    assert scored["parent"] != scored["child"]


def test_the_neighborhood_radius_follows_the_grid_spacing():
    assert field_metrics.half_width_cells(5000.0, 12000.0) == 0
    assert field_metrics.half_width_cells(5000.0, 1000.0) == 5
    assert field_metrics.half_width_cells(5000.0, 1000.0 / 3.0) == 15
    assert field_metrics.minimum_object_cells(25.0, 500.0) == 100
    assert field_metrics.minimum_object_cells(25.0, 12000.0) == 1


def test_identical_fields_score_zero_and_disjoint_echoes_score_one():
    left, right = _echo_pair()
    assert field_metrics.fss_distance(
        left, left, threshold=40.0, half_width=1) == 0.0
    assert field_metrics.fss_distance(
        left, right, threshold=40.0, half_width=0) == 1.0


def test_pooled_rmse_does_not_average_a_loud_window_away():
    """Pooling is by element count, and over equal windows it dominates.

    The pooled value is the quadratic mean of the per-window RMSEs, which is
    strictly above their arithmetic mean whenever the windows differ -- so one
    loud window survives a run of quiet ones instead of being averaged out.
    """
    quiet = np.zeros(100, dtype=np.float64)
    loud = np.full(100, 10.0, dtype=np.float64)
    pooled = field_metrics.aggregate_rmse([quiet, quiet, quiet, loud])
    per_window_mean = 0.25 * (3.0 * field_metrics.rmse(quiet, quiet)
                              + field_metrics.rmse(loud, quiet))
    assert pooled > per_window_mean
    assert pooled == pytest.approx(np.sqrt(100.0 * 100.0 / 400.0), rel=1e-12)


def test_object_timing_returns_the_quiet_sentinel_it_is_given():
    quiet = {300: np.zeros((1, 5, 5)), 600: np.zeros((1, 5, 5))}
    assert field_metrics.first_object_time(
        quiet, threshold=40.0, min_cells=1, quiet_time_seconds=900) == 900.0
    active = dict(quiet)
    active[600] = np.full((1, 5, 5), 45.0)
    assert field_metrics.first_object_time(
        active, threshold=40.0, min_cells=1, quiet_time_seconds=900) == 600.0


def test_the_generic_module_carries_no_campaign_pin():
    source = (Path(field_metrics.__file__)).read_text(encoding="utf-8")
    for pin in ("d01", "d02", "d03", "d04", "REFL_10CM", "12000", "3000.0",
                "40.0", "QVAPOR"):
        assert pin not in source, pin


def test_the_registration_requires_its_start_instant():
    with pytest.raises(TypeError, match="start_time"):
        n5s_metrics.make_registration(run_minutes=30, history_minutes=5)
