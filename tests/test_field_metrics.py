"""The metric extraction moved arithmetic, and moved nothing else.

Two halves, and the second is the load-bearing one:

* the campaign scorer, re-pointed at ``gpuwm.verify.field_metrics``, returns
  the SAME numbers it returned before the move -- compared as ``float.hex()``
  strings against a baseline generated by the pre-move code, so "the same"
  means the same bits and not merely the same to a printed precision; and
* the regression can fail: perturbing one carrier in the synthetic pair moves
  the affected metric off the baseline.  A comparison that cannot fail proves
  nothing about a refactor.

The third pin is the one the extraction exists for: FSS takes its domain's
grid spacing as an argument, so a two-domain pair is scored on BOTH domains
with no key or gate naming either of them.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

import n5s_delegation_fixture as fixture
from gpuwm.verify import field_metrics, n5s_metrics
from gpuwm.verify.n5s_common import write_json

BASELINE_PATH = (
    Path(__file__).with_name("data") / "field_metrics_delegation_baseline.json")


def _baseline() -> dict:
    return json.loads(BASELINE_PATH.read_text(encoding="utf-8"))


def _score_campaign_pair(root: Path, *, perturb_left_seed: int = 0
                         ) -> dict[str, str]:
    """Build the fixture pair and score it through the campaign entry point."""
    baseline = _baseline()
    registration = n5s_metrics.make_registration(
        run_minutes=int(baseline["run_minutes"]),
        history_minutes=int(baseline["history_minutes"]),
        commit="4" * 40, start_time=str(baseline["start_time"]))
    cadence = int(registration["cadence_seconds"])
    duration = int(registration["run_duration_seconds"])
    left = fixture.build_run(
        root, "left", seed=11 + perturb_left_seed,
        domains=n5s_metrics.N5S_DOMAINS, cadence_seconds=cadence,
        duration_seconds=duration, object_second=cadence)
    right = fixture.build_run(
        root, "right", seed=907, domains=n5s_metrics.N5S_DOMAINS,
        cadence_seconds=cadence, duration_seconds=duration,
        object_second=2 * cadence)
    for run in (left, right):
        write_json(run / "n5s-preregistration.json", registration)
        (run / "exit.status").write_text("0\n", encoding="utf-8")
        n5s_metrics._artifact(
            run, root, run_id=run.name, registration=registration)
    return fixture.as_hex(
        n5s_metrics.score_run_pair(left, right, registration, registration))


@pytest.fixture(scope="module")
def delegated_scores(tmp_path_factory) -> dict[str, str]:
    return _score_campaign_pair(tmp_path_factory.mktemp("delegation"))


def test_the_baseline_was_measured_before_the_move(delegated_scores):
    """Every registered number survives the delegation, bit for bit."""
    expected = _baseline()["scores_hex"]
    assert delegated_scores == expected
    assert len(expected) == 61, sorted(expected)


def test_the_regression_can_fail(tmp_path):
    """CONTROL: perturb one side's fields and the comparison must break."""
    perturbed = _score_campaign_pair(tmp_path, perturb_left_seed=1)
    expected = _baseline()["scores_hex"]
    assert set(perturbed) == set(expected)
    assert perturbed != expected


def test_the_campaign_scorer_calls_the_generic_metrics(monkeypatch, tmp_path):
    """The delegation is real: break the generic function, lose the score."""
    def refuse(*args, **kwargs):
        raise AssertionError("generic metric was bypassed")

    monkeypatch.setattr(field_metrics, "state_and_boundary_rmse", refuse)
    with pytest.raises(AssertionError, match="bypassed"):
        _score_campaign_pair(tmp_path)


