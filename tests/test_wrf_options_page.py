"""docs/public/WRF-OPTIONS.md is what the importer actually does.

The breakage this prevents: 2.9.0's CHANGELOG described the refused WRF
physics options in prose, and the prose was narrower than the importer.  It
did not name BMJ cumulus, the ACM2, QNSE, BouLac, TEMF and MRF boundary
layers, the slab, CLM4 and Pleim-Xiu land models, the P3 variants, RRTMG-K or
fast RRTMG, all of which the importer refused.  The page is now generated by
asking the importer about every option WRF v4.7.1 declares; this test fails
when a code change makes the page stale.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _tool():
    spec = importlib.util.spec_from_file_location(
        "build_wrf_option_coverage", ROOT / "tools" / "build_wrf_option_coverage.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_the_page_is_the_importers_answer_for_every_wrf_option():
    tool = _tool()
    text, problems = tool.build()
    assert problems == [], problems
    assert (ROOT / "docs" / "public" / "WRF-OPTIONS.md").read_text(
        encoding="utf-8") == text, (
        "docs/public/WRF-OPTIONS.md is stale: run "
        "python tools/build_wrf_option_coverage.py")


def test_every_wrf_selector_value_has_a_row():
    table = json.loads((ROOT / "gpuwm" / "data" / "wrf_namelist"
                        / "physics_options_v4.7.1.json").read_text(encoding="utf-8"))
    page = (ROOT / "docs" / "public" / "WRF-OPTIONS.md").read_text(encoding="utf-8")
    for kind in ("selectors", "switches"):
        for key, rows in table[kind].items():
            assert f"## `{key}`" in page, key
    # The options 2.9.0's prose list left out are on the page, by name.
    for needle in ("Betts-Miller-Janjic", "ACM2", "Pleim-Xiu LSM",
                   "thermal diffusion scheme", "p3_2category", "rrtmg-k"):
        assert needle in page, needle


def test_the_ocean_mixed_layer_imports():
    tool = _tool()
    assert tool.probe("sf_ocean_physics", 1)["imports"] is True
    # WRF's 3-D PWP ocean is ported (lane/cap-slab-ocean, aa6bdeed308).
    assert tool.probe("sf_ocean_physics", 2)["imports"] is True
